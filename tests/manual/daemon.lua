local cg = require("code_atlas")
local watcher = require("code_atlas.watcher")
local ctx = require("code_atlas.project").context()
print("before:", vim.inspect({ watcher.daemon_state(ctx) }))
watcher.start_daemon(ctx)
vim.wait(2500)
print("after start:", vim.inspect({ watcher.daemon_state(ctx) }))
print("files:", vim.inspect(vim.fn.globpath(ctx.index_dir, "*", false, true)))
print("effective:", watcher.effective_mode(ctx))
watcher.stop_daemon(ctx)
vim.wait(1500)
print("after stop:", vim.inspect({ watcher.daemon_state(ctx) }))
